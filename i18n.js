  const currentLocale = normalizeLocale(detectRawLanguage());
  const currentHtmlLang = HTML_LANG_MAP[currentLocale] || 'en';

  function getLocale() {
    return currentLocale;
  }

  function getHtmlLang() {
    return currentHtmlLang;
  }

  function t(key, vars = {}) {
    const dict = MESSAGES[currentLocale] || MESSAGES.en;
    const raw =
      (dict && Object.prototype.hasOwnProperty.call(dict, key) && dict[key]) ||
      (MESSAGES.en && Object.prototype.hasOwnProperty.call(MESSAGES.en, key) && MESSAGES.en[key]) ||
      key;
    if (typeof raw !== 'string') return String(key);
    return raw.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, token) => {
      if (vars && Object.prototype.hasOwnProperty.call(vars, token)) {
        const val = vars[token];
        if (val !== undefined && val !== null) return String(val);
      }
      return match;
    });
  }

  function localizeDocument(root) {
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = currentHtmlLang;
    }
    const target = root || (typeof document !== 'undefined' ? document : null);
    if (!target || typeof target.querySelectorAll !== 'function') return;

    const applyAttr = (attr, setter) => {
      if (typeof target.hasAttribute === 'function' && target.hasAttribute(attr)) {
        setter(target, target.getAttribute(attr));
      }
      const nodes = target.querySelectorAll(`[${attr}]`);
      for (const el of nodes) {
        const key = el.getAttribute(attr);
        if (key) setter(el, key);
      }
    };

    applyAttr('data-i18n', (el, key) => {
      el.textContent = t(key);
    });
    applyAttr('data-i18n-title', (el, key) => {
      el.title = t(key);
    });
    applyAttr('data-i18n-placeholder', (el, key) => {
      el.placeholder = t(key);
    });
    applyAttr('data-i18n-aria-label', (el, key) => {
      el.setAttribute('aria-label', t(key));
    });
  }

